export function getLocalizedText(
  key: string,
  lang: RegionalLanguageCode = "en",
  defaultFallback?: string
): string {
  if (REGIONAL_DICTIONARY[key] && REGIONAL_DICTIONARY[key][lang]) {
    return REGIONAL_DICTIONARY[key][lang];
  }
  if (REGIONAL_DICTIONARY[key] && REGIONAL_DICTIONARY[key]["en"]) {
    return REGIONAL_DICTIONARY[key]["en"];
  }
  return defaultFallback || key;
}
